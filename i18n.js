function normalizeLang(code) {
  const c = String(code || '').trim();
  if (!c) return 'en';
  if (PP_LANG_CODES.includes(c)) return c;
  const lower = c.toLowerCase();
  const map = {
    'zh': 'zh-CN',
    'zh-cn': 'zh-CN',
    'zh-hans': 'zh-CN',
    'zh-sg': 'zh-CN',
    'zh-tw': 'zh-CHT',
    'zh-hk': 'zh-CHT',
    'zh-mo': 'zh-CHT',
    'zh-hant': 'zh-CHT',
    'nb': 'no',
    'nn': 'no',
    'pt-pt': 'pt',
    'pt_br': 'pt-BR'
  };
  if (map[lower]) return map[lower];
  const base = c.split(/[-_]/)[0];
  if (PP_LANG_CODES.includes(base)) return base;
  const hit = PP_LANG_CODES.find((x) => x.toLowerCase() === lower || x.toLowerCase().startsWith(base.toLowerCase() + '-'));
  return hit || 'en';
}

function isRtl(lang) {
  return RTL.has(normalizeLang(lang));
}

function t(lang, key) {
  const code = normalizeLang(lang);
  const pack = STRINGS[code] || STRINGS.en;
  return pack[key] || STRINGS.en[key] || key;
}

function bundle(lang) {
  const code = normalizeLang(lang);
  const out = { lang: code, rtl: isRtl(code), strings: {} };
  for (const key of Object.keys(STRINGS.en)) {
    out.strings[key] = t(code, key);
  }
  return out;
}

/** 校验：每个 Photopea 语言都有完整键，且与 en 键集合一致 */
function assertComplete() {
  const keys = Object.keys(STRINGS.en).sort();
  const missing = [];
  for (const code of PP_LANG_CODES) {
    if (!STRINGS[code]) {
      missing.push(code + ': (missing pack)');
      continue;
    }
    for (const k of keys) {
      if (!STRINGS[code][k]) missing.push(code + ':' + k);
    }
  }
  return missing;
}

